import { mkdir, readFile, writeFile } from 'node:fs/promises';
await mkdir('generated', { recursive: true });
const files = { html: 'src/index.html', css: 'src/style.css', js: 'src/client.js', planner: 'src/planner.js' };
let output = '// Generated by scripts/build.mjs.\n';
for (const [name, file] of Object.entries(files)) {
  output += `export const ${name} = ${JSON.stringify(await readFile(file, 'utf8'))};\n`;
}
await writeFile('generated/assets.js', output);
