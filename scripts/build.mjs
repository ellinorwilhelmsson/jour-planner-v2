import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { build } from 'esbuild';
await mkdir('generated', { recursive: true });
await build({entryPoints:['src/export.js'],bundle:true,format:'esm',platform:'browser',outfile:'generated/export.js',minify:true});
const files = { html: 'src/index.html', css: 'src/style.css', js: 'src/client.js', planner: 'src/planner.js', model: 'src/model.js', dates: 'src/dates.js', cleaning: 'src/cleaning.js', seed: 'src/seed.js' };
let output = '// Generated by scripts/build.mjs.\n';
for (const [name, file] of Object.entries(files)) {
  output += `export const ${name} = ${JSON.stringify(await readFile(file, 'utf8'))};\n`;
}
output+=`export const exporter = ${JSON.stringify(await readFile('generated/export.js','utf8'))};\n`;
await writeFile('generated/assets.js', output);
